-- FR1 Tool registry: one row per tool that agents may call through the gateway.
CREATE TABLE tools (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(64)   NOT NULL,
    description  VARCHAR(2000) NOT NULL,
    input_schema JSONB         NOT NULL,          -- JSON Schema of the tool's arguments
    risk_level   VARCHAR(10)   NOT NULL,
    owner_team   VARCHAR(100)  NOT NULL,
    kind         VARCHAR(10)   NOT NULL,
    http_method  VARCHAR(10),                     -- REST tools only
    base_url     VARCHAR(500),                    -- REST tools only
    path         VARCHAR(500),                    -- REST tools only
    enabled      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ   NOT NULL,
    updated_at   TIMESTAMPTZ   NOT NULL,

    CONSTRAINT uk_tools_name UNIQUE (name),
    CONSTRAINT ck_tools_risk_level CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_tools_kind CHECK (kind IN ('REST', 'MCP')),
    -- Safety net in the database itself: a REST tool without a target can never be stored.
    CONSTRAINT ck_tools_rest_target CHECK (
        kind <> 'REST' OR (http_method IS NOT NULL AND base_url IS NOT NULL AND path IS NOT NULL))
);
