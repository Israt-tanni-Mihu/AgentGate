-- FR1: downstream MCP servers. Their tools are imported into "tools" (kind = MCP, base_url = the server URL).
CREATE TABLE mcp_servers (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(64)  NOT NULL,
    url                VARCHAR(500) NOT NULL,          -- the server's Streamable HTTP endpoint, e.g. http://localhost:8081/mcp
    owner_team         VARCHAR(100) NOT NULL,
    default_risk_level VARCHAR(10)  NOT NULL,          -- risk level given to NEWLY imported tools
    created_at         TIMESTAMPTZ  NOT NULL,

    CONSTRAINT uk_mcp_servers_name UNIQUE (name),
    CONSTRAINT ck_mcp_servers_risk CHECK (default_risk_level IN ('LOW', 'MEDIUM', 'HIGH'))
);
