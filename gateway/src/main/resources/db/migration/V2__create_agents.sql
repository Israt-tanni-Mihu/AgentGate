-- FR2 Agent identity: one row per AI agent (an OAuth2 client that uses the client credentials grant).
CREATE TABLE agents (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id          VARCHAR(64)  NOT NULL,
    client_secret_hash VARCHAR(200) NOT NULL,   -- BCrypt hash; the plain secret is never stored
    display_name       VARCHAR(100) NOT NULL,
    clearance          VARCHAR(10)  NOT NULL,   -- used later by redaction (FR5)
    enabled            BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ  NOT NULL,
    updated_at         TIMESTAMPTZ  NOT NULL,

    CONSTRAINT uk_agents_client_id UNIQUE (client_id),
    CONSTRAINT ck_agents_clearance CHECK (clearance IN ('LOW', 'HIGH'))
);
