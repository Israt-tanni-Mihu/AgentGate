-- FR3 Policies: one row per version of the gateway's policy set.
-- A version's rules are one JSON snapshot, so an activated version can never change behind our back.
CREATE TABLE policy_versions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      INT          NOT NULL,
    status       VARCHAR(10)  NOT NULL,             -- DRAFT, ACTIVE or RETIRED (was active before)
    dry_run      BOOLEAN      NOT NULL DEFAULT FALSE,
    description  VARCHAR(500),
    rules        JSONB        NOT NULL,             -- list of rules, see docs/policies.md
    created_at   TIMESTAMPTZ  NOT NULL,
    activated_at TIMESTAMPTZ,

    CONSTRAINT uk_policy_versions_version UNIQUE (version),
    CONSTRAINT ck_policy_versions_status CHECK (status IN ('DRAFT', 'ACTIVE', 'RETIRED'))
);

-- The database itself guarantees that at most ONE version is active.
CREATE UNIQUE INDEX uk_policy_versions_one_active ON policy_versions (status) WHERE status = 'ACTIVE';
