-- FR6: every tool is READ or WRITE. Existing REST tools: GET = READ, every other method = WRITE (fail safe).
ALTER TABLE tools ADD COLUMN access_mode VARCHAR(10);
UPDATE tools SET access_mode = CASE WHEN kind = 'REST' AND http_method = 'GET' THEN 'READ' ELSE 'WRITE' END;
ALTER TABLE tools ALTER COLUMN access_mode SET NOT NULL;
ALTER TABLE tools ADD CONSTRAINT ck_tools_access_mode CHECK (access_mode IN ('READ', 'WRITE'));

-- FR8 kill switch: one row per switch. engaged = FALSE keeps the row, so the history of switches is kept.
-- target = agent client id, tool name, or '*' for ALL_WRITES.
CREATE TABLE kill_switches (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope       VARCHAR(16)  NOT NULL,
    target      VARCHAR(100) NOT NULL,
    engaged     BOOLEAN      NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,

    CONSTRAINT uk_kill_switches_scope_target UNIQUE (scope, target),
    CONSTRAINT ck_kill_switches_scope CHECK (scope IN ('AGENT', 'TOOL', 'ALL_WRITES'))
);

-- FR6 alerts raised by breached limits. Generic enough for later alert types.
CREATE TABLE alerts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_type  VARCHAR(40)  NOT NULL,
    agent_id    VARCHAR(64),
    tool_name   VARCHAR(64),
    message     VARCHAR(500) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL
);
CREATE INDEX ix_alerts_created_at ON alerts (created_at);
